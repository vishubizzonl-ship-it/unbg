// Stand-in for @imgly/background-removal so the worker contract can be tested
// without downloading a 44 MB model. Mirrors the real signature.
export async function removeBackground(file, config = {}) {
  const bytes = new Uint8Array(await file.arrayBuffer());
  const progress = config.progress ?? (() => {});
  const total = 4;
  for (let i = 1; i <= total; i++) progress('fetch:model', i, total);
  if (bytes.length === 0) throw new Error('empty input');
  if (bytes[0] === 0x00) throw new Error('stub: undecodable');
  progress('inference', total, total);
  // a 1x1 transparent PNG
  const png = new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
    0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae,
    0x42, 0x60, 0x82,
  ]);
  return new Blob([png], { type: 'image/png' });
}
